/** Цвет человека. Не украшение: по нему читается авторство свидания. */
export type PersonColor = 'ember' | 'iris';

/**
 * Цвета людей — ссылками на CSS-переменные, а не жёсткими hex.
 *
 * Значения различаются в тёмной и светлой теме (на светлом акценты темнеют
 * до контраста 4.5:1), поэтому подставлять сюда константу нельзя: в инлайновом
 * стиле она не переключится вместе с темой.
 */
export const PERSON_VAR: Record<PersonColor, string> = {
  ember: 'var(--ember)', // Влад
  iris: 'var(--iris)', // Ангелина
};

/**
 * CSS-переменная, которой подсвечиваются элементы текущего пользователя.
 * Значение выставляется на корне приложения после входа.
 */
export const PERSON_COLOR_VAR = '--person-color';
