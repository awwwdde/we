"""Схема прогноза погоды на дату свидания."""

from pydantic import BaseModel


class WeatherOut(BaseModel):
    """Прогноз на момент свидания.

    Ровно то, что помещается в одну строку карточки: сколько градусов,
    что за погода словом и стоит ли брать зонт. Всё остальное, что отдаёт
    Open-Meteo, приложению не нужно.
    """

    temp_c: int
    # Код WMO. Хранится, чтобы фронт мог однажды подобрать свою подпись,
    # не переучивая сервер.
    code: int
    description: str
    precipitation_chance: int | None = None
    # Прогноз старше шести часов: сервис не ответил, показываем прежний.
    stale: bool = False
